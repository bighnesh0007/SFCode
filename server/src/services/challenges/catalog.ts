/**
 * Loads every problem under server/problems at startup and validates it.
 *
 * A malformed problem throws, which stops the server: shipping a problem whose
 * starter and hidden tests disagree would make it unpassable, and that is worse
 * than a failed deploy.
 */
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";
import { TRACKS, type ApexFileType, type Challenge, type ChallengeFile } from "../../domain/challenge.ts";
import { DIFFICULTY_IDS } from "../../domain/difficulty.ts";

// Apex identifiers; the `Sfc` prefix keeps them clear of names already in a learner's org.
const apexName = z.string().regex(/^Sfc[A-Za-z0-9_]{1,37}$/, "must be an Apex name starting with Sfc");

/** Generated by the grader around the user's query; no problem may declare this name. */
export const SOQL_SUBMISSION_CLASS = "SfcSoqlSubmission";
/** Replaced with the reference query as an Apex string literal when tests are packaged. */
export const REFERENCE_PLACEHOLDER = "{{REFERENCE_QUERY}}";
/**
 * Replaced with problems/_shared/soqlCompare.apex. Pasted INTO the test class
 * rather than deployed as its own class: test classes are exempt from the 75%
 * coverage rule, a helper class would not be.
 */
export const COMPARE_PLACEHOLDER = "{{SOQL_COMPARE}}";
const RESERVED = new Set([SOQL_SUBMISSION_CLASS.toLowerCase()]);

const apexFile = z.strictObject({ name: apexName, type: z.enum(["class", "trigger"]) });
const soqlFile = z.strictObject({ name: z.literal("query"), type: z.literal("soql") });

const problemJson = z.strictObject({
  title: z.string().min(3).max(120),
  track: z.enum(TRACKS).default("apex"),
  difficulty: z.enum(DIFFICULTY_IDS),
  category: z.string().min(2).max(40),
  order: z.number().int().positive(),
  tags: z.array(z.string().min(1).max(40)).max(8).default([]),
  // Flow problems have none: the learner builds the flow in Salesforce.
  files: z.array(z.union([apexFile, soqlFile])).max(5),
  flow: z
    .strictObject({
      // Flow API names: letters, digits, underscores; SFC_ keeps them clear of the learner's own.
      apiName: z.string().regex(/^SFC_[A-Za-z0-9_]{1,76}$/, "must start with SFC_"),
      kind: z.enum(["record-triggered", "autolaunched"]),
    })
    .optional(),
  // Apex test class; LWC problems use tests/<component>.test.js instead.
  testClass: apexName.optional(),
  lwc: z.strictObject({ component: z.string().regex(/^[a-z][a-zA-Z0-9]{0,39}$/) }).optional(),
});

const SLUG = /^[a-z0-9]+(-[a-z0-9]+)*$/;
export const MAX_HINTS = 3;

export const extensionFor = (type: ApexFileType): string => ({ class: "cls", trigger: "trigger", soql: "soql" })[type];

function readSources(dir: string, files: ChallengeFile[], what: string): Record<string, string> {
  const expected = new Set(files.map((f) => `${f.name}.${extensionFor(f.type)}`));
  const present = existsSync(dir) ? readdirSync(dir) : [];
  const extra = present.filter((f) => !expected.has(f));
  if (extra.length) throw new Error(`${what} has unexpected files: ${extra.join(", ")}`);
  const out: Record<string, string> = {};
  for (const f of files) {
    const path = join(dir, `${f.name}.${extensionFor(f.type)}`);
    if (!existsSync(path)) throw new Error(`${what} is missing ${f.name}.${extensionFor(f.type)}`);
    out[f.name] = readFileSync(path, "utf8");
  }
  return out;
}

/**
 * A flow problem's reference is the flow's metadata, used only by
 * verify:problems to prove the problem is solvable. Keyed by API name.
 */
function readFlowReference(dir: string, apiName: string, where: string): Record<string, string> {
  const file = `${apiName}.flow-meta.xml`;
  const present = existsSync(dir) ? readdirSync(dir) : [];
  if (present.length !== 1 || present[0] !== file) throw new Error(`${where}/reference must contain exactly ${file}`);
  const xml = readFileSync(join(dir, file), "utf8");
  if (!/<Flow\b/.test(xml) || !xml.includes("<status>Active</status>")) throw new Error(`${where}: reference flow must be a <Flow> with <status>Active</status>`);
  return { [apiName]: xml };
}

export const LWC_PARTS = ["html", "js", "css"] as const;

/** An LWC problem's three component files, keyed by extension. */
function readLwcSources(dir: string, component: string, what: string): Record<string, string> {
  const expected = LWC_PARTS.map((ext) => `${component}.${ext}`);
  const present = existsSync(dir) ? readdirSync(dir).sort() : [];
  if (present.join() !== [...expected].sort().join()) throw new Error(`${what} must contain exactly ${expected.join(", ")}`);
  return Object.fromEntries(LWC_PARTS.map((ext) => [ext, readFileSync(join(dir, `${component}.${ext}`), "utf8")]));
}

/** LWC problems share the catalog but nothing of the Apex grading path. */
function loadLwcChallenge(dir: string, slug: string, meta: z.infer<typeof problemJson>, component: string): Challenge {
  const where = `problems/${slug}`;
  if (meta.files.length > 0 || meta.flow || meta.testClass) throw new Error(`${where}: an lwc problem has an "lwc" block and no files, flow or testClass`);
  const testsPath = join(dir, "tests", `${component}.test.js`);
  if (!existsSync(testsPath)) throw new Error(`${where}: missing tests/${component}.test.js`);
  const tests = readFileSync(testsPath, "utf8");
  if (!/\bconst tests\s*=/.test(tests)) throw new Error(`${where}: the test file must define \`const tests = [...]\``);
  // Hidden tests grade submissions on the server (in the sandbox); they never reach the browser.
  const hiddenPath = join(dir, "tests", `${component}.hidden.test.js`);
  if (!existsSync(hiddenPath)) throw new Error(`${where}: missing tests/${component}.hidden.test.js (the tests that grade submissions)`);
  const hiddenTests = readFileSync(hiddenPath, "utf8");
  if (!/\bconst tests\s*=/.test(hiddenTests)) throw new Error(`${where}: the hidden test file must define \`const tests = [...]\``);
  const starter = readLwcSources(join(dir, "starter"), component, `${where}/starter`);
  const reference = readLwcSources(join(dir, "reference"), component, `${where}/reference`);
  return {
    slug,
    title: meta.title,
    track: meta.track,
    difficulty: meta.difficulty,
    category: meta.category,
    order: meta.order,
    tags: meta.tags,
    statement: readFileSync(join(dir, "statement.md"), "utf8"),
    files: [],
    starter,
    reference,
    // Unused for LWC (no Apex deploy); kept so Challenge has one shape.
    testClass: { name: `${component}.test.js`, source: tests },
    lwc: { component, tests, hiddenTests },
  };
}

/** Optional learning aids next to the problem: up to three hints, cheapest first, and a write-up. */
const hintsJson = z.array(z.string().trim().min(10).max(600)).min(1).max(MAX_HINTS);

export function loadChallenge(root: string, slug: string): Challenge {
  const c = loadCore(root, slug);
  const dir = join(root, slug);
  const hintsPath = join(dir, "hints.json");
  if (existsSync(hintsPath)) {
    const parsed = hintsJson.safeParse(JSON.parse(readFileSync(hintsPath, "utf8")));
    if (!parsed.success) throw new Error(`problems/${slug}/hints.json: ${parsed.error.issues.map((i) => `${i.path.join(".")}: ${i.message}`).join("; ")}`);
    c.hints = parsed.data;
  }
  const editorialPath = join(dir, "editorial.md");
  if (existsSync(editorialPath)) {
    const text = readFileSync(editorialPath, "utf8").trim();
    if (text.length < 50) throw new Error(`problems/${slug}/editorial.md is too short to help anyone`);
    c.editorial = text;
  }
  return c;
}

function loadCore(root: string, slug: string): Challenge {
  if (!SLUG.test(slug)) throw new Error(`problem folder "${slug}" is not a kebab-case slug`);
  const dir = join(root, slug);
  const where = `problems/${slug}`;
  const parsed = problemJson.safeParse(JSON.parse(readFileSync(join(dir, "problem.json"), "utf8")));
  if (!parsed.success) throw new Error(`${where}/problem.json: ${parsed.error.issues.map((i) => `${i.path.join(".")}: ${i.message}`).join("; ")}`);
  const meta = parsed.data;

  if ((meta.track === "lwc") !== (meta.lwc !== undefined)) throw new Error(`${where}: the "lwc" block belongs to lwc-track problems only`);
  if (meta.lwc) return loadLwcChallenge(dir, slug, meta, meta.lwc.component);
  if (!meta.testClass) throw new Error(`${where}: testClass is required`);
  const testClass = meta.testClass;
  const testPath = join(dir, "tests", `${testClass}.cls`);
  if (meta.track === "flow" ? !meta.flow || meta.files.length > 0 : meta.flow !== undefined || meta.files.length === 0) {
    throw new Error(`${where}: a flow-track problem has a "flow" block and no files; other problems have files and no "flow"`);
  }
  return buildChallenge(
    {
      slug,
      meta: { ...meta, testClass },
      statement: readFileSync(join(dir, "statement.md"), "utf8"),
      starter: readSources(join(dir, "starter"), meta.files, `${where}/starter`),
      reference: meta.flow ? readFlowReference(join(dir, "reference"), meta.flow.apiName, where) : readSources(join(dir, "reference"), meta.files, `${where}/reference`),
      testSource: existsSync(testPath) ? readFileSync(testPath, "utf8") : null,
    },
    where,
  );
}

/** A problem's parts in memory: from files (built-in) or from the database (community). */
export interface ChallengeSource {
  slug: string;
  meta: Omit<z.infer<typeof problemJson>, "lwc" | "testClass"> & { testClass: string };
  statement: string;
  starter: Record<string, string>;
  reference: Record<string, string>;
  /** null = the test class file is missing. */
  testSource: string | null;
}

/** problem.json's shape, for callers building a ChallengeSource themselves. */
export const problemMetaSchema = problemJson;

/**
 * Validates a non-LWC problem and returns it. Every rule here applies to
 * built-in and community problems alike. `where` prefixes error messages.
 */
export function buildChallenge(src: ChallengeSource, where: string): Challenge {
  const { slug, meta } = src;
  if (!SLUG.test(slug)) throw new Error(`${where}: "${slug}" is not a kebab-case slug`);
  const testClass = meta.testClass;
  if (!apexName.safeParse(testClass).success) throw new Error(`${where}: test class ${testClass} must be an Apex name starting with Sfc`);

  if (meta.track === "flow" ? !meta.flow || meta.files.length > 0 : meta.flow !== undefined || meta.files.length === 0) {
    throw new Error(`${where}: a flow-track problem has a "flow" block and no files; other problems have files and no "flow"`);
  }
  if (meta.track === "lwc") throw new Error(`${where}: LWC problems are built from their own folder layout`);

  const names = [...meta.files.map((f) => f.name), testClass];
  if (new Set(names).size !== names.length) throw new Error(`${where}: file and test class names must be unique`);
  const reserved = names.find((n) => RESERVED.has(n.toLowerCase()));
  if (reserved) throw new Error(`${where}: ${reserved} is reserved for the SOQL grader`);
  const hasSoql = meta.files.some((f) => f.type === "soql");
  if (meta.track === "soql" ? !(hasSoql && meta.files.length === 1) : hasSoql) {
    throw new Error(`${where}: a soql-track problem has exactly one soql file, and only soql-track problems have one`);
  }

  if (src.testSource === null) throw new Error(`${where}: missing tests/${testClass}.cls`);
  const testSource = src.testSource;
  if (!/@isTest/i.test(testSource)) throw new Error(`${where}: hidden test class has no @isTest`);
  if (/SeeAllData\s*=\s*true/i.test(testSource)) throw new Error(`${where}: hidden tests must not use SeeAllData=true`);
  // Long text areas cannot be filtered in SOQL; such a test fails for every
  // submission, correct or not. Description is the one problems reach for.
  if (/\bWHERE\b[^\]]*\bDescription\b/i.test(testSource)) throw new Error(`${where}: hidden tests filter on Description (a long text area — not filterable)`);

  const { starter, reference } = src;
  // Each file must declare the type and name problem.json promises, or the deploy fails confusingly.
  for (const f of meta.files) {
    const decl =
      f.type === "class"
        ? new RegExp(`\\bclass\\s+${f.name}\\b`, "i")
        : f.type === "trigger"
          ? new RegExp(`^\\s*trigger\\s+${f.name}\\s+on\\b`, "im")
          : /^\s*SELECT\b/i;
    for (const [label, src] of [["starter", starter], ["reference", reference]] as const) {
      if (!decl.test(src[f.name] ?? "")) throw new Error(`${where}/${label}/${f.name}: does not declare ${f.type} ${f.name}`);
    }
  }

  if (meta.track === "debug" && meta.files.every((f) => starter[f.name]?.trim() === reference[f.name]?.trim())) {
    throw new Error(`${where}: a debugging problem's starter must contain the bug (it equals the reference)`);
  }

  if (meta.track === "soql") {
    // The reference query lives ONLY in reference/query.soql; tests receive it via the placeholder.
    if (!testSource.includes(REFERENCE_PLACEHOLDER)) throw new Error(`${where}: SOQL tests must use ${REFERENCE_PLACEHOLDER}`);
    if (!testSource.includes("sfcRunSubmission()")) throw new Error(`${where}: SOQL tests never run the submission (sfcRunSubmission())`);
    if (!testSource.includes(COMPARE_PLACEHOLDER)) throw new Error(`${where}: SOQL tests must include ${COMPARE_PLACEHOLDER}`);
  }

  return {
    slug,
    title: meta.title,
    track: meta.track,
    difficulty: meta.difficulty,
    category: meta.category,
    order: meta.order,
    tags: meta.tags,
    statement: src.statement,
    files: meta.files,
    starter,
    reference,
    testClass: { name: testClass, source: testSource },
    ...(meta.flow ? { flow: meta.flow } : {}),
  };
}

export class ChallengeCatalog {
  private readonly bySlug = new Map<string, Challenge>();
  private readonly orders = new Map<number, string>();
  private readonly orgNames = new Map<string, string>();

  /** `soqlCompare`: the shared comparison helper pasted into SOQL tests ("" when no SOQL problems). */
  constructor(
    challenges: Challenge[],
    readonly soqlCompare = "",
  ) {
    if (challenges.some((c) => c.track === "soql")) {
      if (!soqlCompare.trim()) throw new Error("SOQL problems need problems/_shared/soqlCompare.apex");
      if (soqlCompare.includes(REFERENCE_PLACEHOLDER) || soqlCompare.includes(COMPARE_PLACEHOLDER)) {
        throw new Error("problems/_shared/soqlCompare.apex must not contain a {{placeholder}} (it would survive packaging)");
      }
      for (const fn of ["sfcRunSubmission", "sfcAssertSameRows", `${SOQL_SUBMISSION_CLASS}.QUERY`]) {
        if (!soqlCompare.includes(fn)) throw new Error(`problems/_shared/soqlCompare.apex must define/use ${fn}`);
      }
    }
    for (const c of [...challenges].sort((a, b) => a.order - b.order)) this.add(c);
  }

  /** Org-global names a problem deploys (Apex classes, triggers, the flow). LWC deploys nothing. */
  private static namesOf(c: Challenge): string[] {
    return c.lwc ? [] : [...c.files.filter((f) => f.type !== "soql").map((f) => f.name), c.testClass.name, ...(c.flow ? [c.flow.apiName] : [])];
  }

  /** Why `c` can't join the catalog, or null. Slugs, orders and Apex names must be unique. */
  conflict(c: Challenge): string | null {
    if (this.bySlug.has(c.slug)) return `the slug ${c.slug} is taken`;
    const byOrder = this.orders.get(c.order);
    if (byOrder) return `duplicate order ${c.order} (also ${byOrder})`;
    // Apex names are org-global; two problems sharing one would grade against each other's code.
    for (const n of ChallengeCatalog.namesOf(c)) {
      const other = this.orgNames.get(n.toLowerCase());
      if (other) return `Apex name ${n} is also used by ${other}`;
    }
    return null;
  }

  /** Adds a problem (built-in at startup, community on approval). Throws on a conflict. */
  add(c: Challenge): void {
    const why = this.conflict(c);
    if (why) throw new Error(`problems/${c.slug}: ${why}`);
    this.bySlug.set(c.slug, c);
    this.orders.set(c.order, c.slug);
    for (const n of ChallengeCatalog.namesOf(c)) this.orgNames.set(n.toLowerCase(), c.slug);
  }

  /** Removes a community problem (unpublish). */
  remove(slug: string): void {
    const c = this.bySlug.get(slug);
    if (!c) return;
    this.bySlug.delete(slug);
    this.orders.delete(c.order);
    for (const n of ChallengeCatalog.namesOf(c)) this.orgNames.delete(n.toLowerCase());
  }

  /** The next free order number for community problems (they sort after the built-ins). */
  nextCommunityOrder(): number {
    return Math.max(999, ...this.orders.keys()) + 1;
  }

  static load(root: string): ChallengeCatalog {
    // `_shared/` holds grader support files, not a problem.
    const slugs = readdirSync(root).filter((e) => !e.startsWith("_") && statSync(join(root, e)).isDirectory());
    const comparePath = join(root, "_shared", "soqlCompare.apex");
    return new ChallengeCatalog(
      slugs.map((s) => loadChallenge(root, s)),
      existsSync(comparePath) ? readFileSync(comparePath, "utf8") : "",
    );
  }

  all(): Challenge[] {
    return [...this.bySlug.values()].sort((a, b) => a.order - b.order);
  }

  get(slug: string): Challenge | undefined {
    return this.bySlug.get(slug);
  }
}
